#!/usr/bin/env python3
"""Generates docs/AGENTS.md and docs/WORKFLOWS.md from the plugin's own sources (contracts, agent files, workflows).

  python3 scripts/build_docs.py          write them
  python3 scripts/build_docs.py --check  exit 1 if they are stale (a static test runs this)
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "plugins" / "factory" / "lib"))

from factory_core import catalog, config, registry  # noqa: E402

HEADER = "<!-- Generated by scripts/build_docs.py from the plugin's sources. Do not edit by hand. -->\n\n"


def artifact_line(name: str, artifacts: dict, headers: dict) -> str:
    spec = artifacts.get(name)
    if not spec:
        return name
    pattern = headers.get(spec["header"], {}).get("pattern", "")
    m = re.match(r"\^(.*?)\((.*)\)\$$", pattern)  # "^STATUS: (READY|BLOCKED)$" -> STATUS: READY | STATUS: BLOCKED
    values = " · ".join(f"`{m.group(1)}{v}`" for v in m.group(2).split("|")) if m else f"`{spec['header']}`"
    sections = ", ".join(f"`## {s}`" for s in spec.get("sections", []))
    return f"**{spec.get('label', name)}** — first line {values}; sections {sections or 'none required'}"


def agents_md() -> str:
    cat = catalog.catalog()
    contracts = registry.contracts()
    artifacts, headers = contracts["artifacts"], contracts["headers"]
    out = [HEADER, "# Agents\n",
           f"{len(cat['agents'])} specialists in {len(cat['domains'])} domains. Each is a Claude Code subagent "
           "(`factory:<name>`) whose file has the same ten contract sections — Purpose and scope, Not responsible "
           "for, Inputs, Output contract, Working rules, Verification, Security constraints, Errors and escalation, "
           "Handoff, Success criteria — followed by the shared factory protocol (`plugins/factory/protocol/"
           "protocol.md`, inlined by `scripts/build_agents.py`).\n",
           "Languages are not agents: implementers adapt to the repository's stack after reading `AGENTS.md`/"
           "`CLAUDE.md` and neighbouring code. Agents can also be called directly (\"use the factory:sql-engineer "
           "agent to …\"); without a factory header they work in the current directory and still keep their output "
           "contract and safety rules.\n",
           "| Agent | Domain | Model | Writes | Used by | Evolved from |", "|---|---|---|---|---|---|"]
    domains = {d["id"]: d["title"] for d in cat["domains"]}
    for a in cat["agents"]:
        writes = ", ".join(artifacts.get(o, {}).get("label", o) for o in a["outputs"]) or "code"
        out.append(f"| [`{a['name']}`](#{a['name']}) | {domains.get(a['domain'], a['domain'])} | {a['model']} | {writes} | "
                   f"{', '.join(a['workflows']) or 'plan tasks, quick jobs'} | {a.get('was') or 'new'} |")
    for d in cat["domains"]:
        out += ["", f"## {d['title']}", ""]
        for a in [x for x in cat["agents"] if x["domain"] == d["id"]]:
            c = a.get("contract") or {}
            out += [f"### {a['name']}", "", f"**{a['title']}** · model `{a['model']}` · tools "
                    + ", ".join(f"`{t}`" for t in a["tools"]), "", a["summary"], ""]
            for label, key in (("Scope", "Purpose and scope"), ("Not responsible for", "Not responsible for")):
                body = (c.get(key) or "").strip()
                if body:
                    out += [f"**{label}**", "", body, ""]
            for o in a["outputs"]:
                out += [f"- **Output:** {artifact_line(o, artifacts, headers)}"]
            if a.get("review_key"):
                out += [f"- **Review panel seat:** `{a['review_key']}`"]
            out += [f"- **Workflows:** {', '.join(a['workflows']) or 'called by the orchestrator for quick tasks'}",
                    f"- **File:** `plugins/factory/agents/{a['name']}.md` (source `agents-src/{a['name']}.md`)", ""]
    return "\n".join(out).rstrip() + "\n"


COND = {
    "size_in": lambda v: f"size is {' or '.join(v)}",
    "param_true": lambda v: f"`--param {v}=true`",
    "policy": lambda v: f"policy `{v}`",
    "has_plan": lambda v: "a plan exists" if v else "no plan exists",
}


def when_text(cond) -> str:
    if not cond:
        return ""
    if "any" in cond:
        return " or ".join(when_text(c) for c in cond["any"])
    if "all" in cond:
        return " and ".join(when_text(c) for c in cond["all"])
    if "not" in cond:
        return f"not ({when_text(cond['not'])})"
    return " and ".join(COND[k](v) if k in COND else f"{k}={v}" for k, v in cond.items())


def stage_text(st: dict, roster: dict) -> str:
    kind = st["kind"]
    title = st.get("title", st["id"])
    if kind == "agent":
        who = st.get("agent", "")
        who = "a specialist the orchestrator picks" if str(who).startswith("$") else f"`{who}`"
        what = f"{title} — {who} writes `{st.get('output')}`"
    elif kind == "parallel":
        what = f"{title} — in parallel: " + ", ".join(f"`{m['agent']}` → `{m.get('output')}`" for m in st.get("members", []))
    elif kind == "build":
        what = f"{title} — `{st.get('agent', 'builder')}` builds (plan tasks first when a plan exists), commits, writes `build.md`"
    elif kind == "panel":
        rules = "; ".join(f"+{', '.join(r['add'])} when {r['if']}" for r in st.get("rules", []))
        what = (f"{title} — review panel: always {', '.join(st.get('always', []))}" + (f"; {rules}" if rules else "")
                + f"; any CHANGES loops back to `{st.get('loop_to')}`" if st.get("loop_to") else "")
    elif kind == "gate":
        what = f"{title} — human gate (`/factory build <job>` to continue, `/factory rework <job> <note>`)"
    elif kind == "approve":
        extra = " — always escalates to a human" if st.get("escalate_always") else ""
        what = f"{title} — `approver` decides APPROVE or ESCALATE{extra}"
    elif kind == "merge":
        what = f"{title} — local merge into the base branch (or a ready branch with `deliver: branch`); never pushed"
    elif kind == "deliver":
        what = f"{title} — delivers `{st.get('artifact', st.get('output', 'the report'))}`; nothing is merged"
    elif kind == "setup":
        what = f"{title} — worktree + branch `factory/<job>`" + (", dependencies installed" if st.get("install") else "")
    else:
        what = title
    cond = when_text(st.get("when"))
    return what + (f" *(only when {cond})*" if cond else "")


def workflows_md() -> str:
    cat = catalog.catalog()
    roster = {a["name"]: a for a in cat["agents"]}
    limits = config.DEFAULTS["limits"]
    out = [HEADER, "# Workflows\n",
           "Start one with `/factory <request>` (the orchestrator picks the workflow and size and says why) or name "
           "it: `/factory fix …`, `/factory data …`. Each workflow is a JSON file in `plugins/factory/workflows/`, "
           "validated by the engine and snapshotted into the job when it starts, so an upgrade never changes a "
           "running job.\n",
           f"Limits (defaults, per job; `.factory/config.json` changes them): {limits['max_agent_runs']} agent runs, "
           f"{limits['max_review_rounds']} review rounds, {limits['max_attempts']} attempts per step, "
           f"{limits['max_parallel']} agents at once. Hitting one stops the job for a human; it never continues "
           "silently.\n",
           "| Workflow | Use when | Ends with |", "|---|---|---|"]
    for w in cat["workflows"]:
        wf = registry.load_workflow(w["id"])
        last = wf["stages"][-1]["kind"]
        ends = {"merge": "a local merge (or a ready branch)", "deliver": "a delivered report"}.get(last, last)
        out.append(f"| [`{w['id']}`](#{w['id']}) | {w.get('use_when', '')} | {ends} |")
    for w in cat["workflows"]:
        wf = registry.load_workflow(w["id"])
        out += ["", f"## {w['id']}", "", f"**{w['title']}.** {w.get('summary', '')}", ""]
        if w.get("use_when"):
            out += [f"Use when: {w['use_when']}", ""]
        for i, st in enumerate(wf["stages"], 1):
            out.append(f"{i}. {stage_text(st, roster)}")
        policy = wf.get("policy") or {}
        if policy:
            out += ["", "Policy: " + ", ".join(f"`{k}: {v}`" for k, v in policy.items())]
    out += ["", "## Review panel", "",
            "Code and security reviewers sit on every panel. UX and UI reviewers join when UI files change "
            f"(globs: {', '.join(f'`{g}`' for g in config.DEFAULTS['panel']['ui_globs'][:6])}, …) or the builder "
            "declares `UI impact: yes`; the performance engineer joins for perf and data work or hot paths. "
            "Membership only grows across rounds, every seat records why it was picked, and a round waits for every "
            "reviewer before the builder is resumed."]
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    targets = {ROOT / "docs" / "AGENTS.md": agents_md(), ROOT / "docs" / "WORKFLOWS.md": workflows_md()}
    if "--check" in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, text in targets.items() if not p.exists() or p.read_text() != text]
        if stale:
            print("build_docs: stale: " + ", ".join(stale) + " (run python3 scripts/build_docs.py)")
            return 1
        print("build_docs: generated docs are current")
        return 0
    for p, text in targets.items():
        p.write_text(text)
    print("build_docs: wrote " + ", ".join(str(p.relative_to(ROOT)) for p in targets))
    return 0


if __name__ == "__main__":
    sys.exit(main())
