#!/usr/bin/env python3
"""Generate plugins/factory/agents/<name>.md from the roster, the agent bodies and the shared protocol.

    agents/<name>.md = YAML frontmatter (from contracts/agents.json)
                     + generated-file comment
                     + agents-src/<name>.md
                     + "## Factory protocol" + protocol/protocol.md

Usage:
    python3 scripts/build_agents.py           write every generated file
    python3 scripts/build_agents.py --check   exit 1 and list stale files instead of writing

Python >= 3.9, standard library only. Output is deterministic.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PLUGIN = ROOT / "plugins" / "factory"
ROSTER = PLUGIN / "contracts" / "agents.json"
SOURCES = PLUGIN / "agents-src"
PROTOCOL = PLUGIN / "protocol" / "protocol.md"
OUT = PLUGIN / "agents"

COLORS = {
    "discover": "purple",
    "build": "blue",
    "data": "cyan",
    "infra": "orange",
    "quality": "pink",
    "deliver": "yellow",
}
PROTOCOL_HEADING = "## Factory protocol"
GENERATED_MARK = "<!-- Generated by scripts/build_agents.py"
# Plain YAML scalars may not start with an indicator character or contain ": " or " #".
_PLAIN_SAFE = re.compile(r"^[A-Za-z0-9(][^\n]*$")


def yaml_scalar(value: str) -> str:
    """Render a one-line string as a YAML scalar, double-quoting it only when a plain scalar would be unsafe."""
    if (
        _PLAIN_SAFE.match(value)
        and ": " not in value
        and " #" not in value
        and not value.endswith((":", " "))
    ):
        return value
    return json.dumps(value, ensure_ascii=False)  # a JSON string is a valid YAML double-quoted scalar


def load_roster() -> list[dict]:
    with open(ROSTER, encoding="utf-8") as fh:
        data = json.load(fh)
    return sorted(data["agents"], key=lambda a: a["name"])


def render(agent: dict, body: str, protocol: str) -> str:
    name = agent["name"]
    domain = agent["domain"]
    if domain not in COLORS:
        raise SystemExit(f"build_agents: agent {name!r} has unknown domain {domain!r}")
    front = [
        "---",
        f"name: {name}",
        f"description: {yaml_scalar(agent['summary'])}",
        f"tools: {', '.join(agent['tools'])}",
        f"model: {agent['model']}",
        f"color: {COLORS[domain]}",
        "---",
        f"{GENERATED_MARK} from agents-src/{name}.md and protocol/protocol.md. "
        "Edit those, then run the script. -->",
    ]
    return (
        "\n".join(front)
        + "\n\n"
        + body.strip()
        + f"\n\n{PROTOCOL_HEADING}\n\n"
        + protocol.strip()
        + "\n"
    )


def expected_files() -> tuple[dict[Path, str], list[str]]:
    """Map of generated path -> content, plus problems that make generation impossible."""
    problems: list[str] = []
    roster = load_roster()
    names = [a["name"] for a in roster]
    sources = sorted(p.stem for p in SOURCES.glob("*.md"))
    for stem in sources:
        if stem not in names:
            problems.append(f"agents-src/{stem}.md has no entry in contracts/agents.json")
    for name in names:
        if name not in sources:
            problems.append(f"contracts/agents.json lists {name!r} but agents-src/{name}.md does not exist")
    if not PROTOCOL.exists():
        problems.append("protocol/protocol.md does not exist")
        return {}, problems
    protocol = PROTOCOL.read_text(encoding="utf-8")
    files: dict[Path, str] = {}
    for agent in roster:
        src = SOURCES / f"{agent['name']}.md"
        if src.exists():
            files[OUT / f"{agent['name']}.md"] = render(agent, src.read_text(encoding="utf-8"), protocol)
    return files, problems


def generated_strays(expected: dict[Path, str]) -> list[Path]:
    """Generated files in agents/ whose agent is no longer in the roster."""
    out = []
    for path in sorted(OUT.glob("*.md")):
        if path not in expected and GENERATED_MARK in path.read_text(encoding="utf-8"):
            out.append(path)
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="report stale files instead of writing them")
    args = parser.parse_args(argv)

    files, problems = expected_files()
    for problem in problems:
        print(f"error: {problem}", file=sys.stderr)

    rel = lambda p: p.relative_to(ROOT).as_posix()  # noqa: E731
    if args.check:
        stale = []
        for path, content in sorted(files.items()):
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current != content:
                stale.append(f"{rel(path)} ({'missing' if current is None else 'out of date'})")
        stale += [f"{rel(p)} (agent no longer in the roster)" for p in generated_strays(files)]
        for line in stale:
            print(f"stale: {line}", file=sys.stderr)
        if stale or problems:
            print("Run: python3 scripts/build_agents.py", file=sys.stderr)
            return 1
        print(f"build_agents: {len(files)} agent files are current")
        return 0

    if problems:
        return 1
    OUT.mkdir(parents=True, exist_ok=True)
    written = 0
    for path, content in sorted(files.items()):
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            with open(path, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(content)
            written += 1
    for path in generated_strays(files):
        path.unlink()
        print(f"removed {rel(path)}")
    print(f"build_agents: {len(files)} agent files, {written} written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
